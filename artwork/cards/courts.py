def fluting(x, y, length, width, rotation, shadow, light):
    """Alternating knife-shaped shadow and paper sliver along a silk or velvet fold."""
    d = 'M0 0 Q1.75 3.6 1.15 6.35 Q.35 8.81 -1.05 10 Q-.02 7.35 .13 5.87 Q.75 3.06 0 0Z'
    h = 'M-.52 1.12 Q.25 4.04 -.15 5.58 Q-.38 7.05 -1.1 8.1 Q-.39 5.08 -.52 1.12Z'
    return put(plate(d,shadow)+plate(h,light),x,y,width,rotation,length/10)


