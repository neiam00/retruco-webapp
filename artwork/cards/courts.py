def plate(d, pigment):
    """A cut with unequal ends, or a flat deposit of a second ink."""
    return p(d, pigment, 0, 'none')


def hair_lock(x, y, scale, turn, light):
    cut = plate('M-1.3 -.6 C-1.2 -2.8 1.6 -2.6 1.4 -.6 C1.2 .9 -.7 1.1 -.6 2.4 Q-1.7 1.5 -.9 .6 Q1.1 -.5 .7 -1.4 Q.1 -2.3 -1.3 -.6Z', light)
    return put(cut, x, y, scale, turn)


