        rows={2:[(44.5,39.8),(44.5,96)],3:[(31.6,32.7),(57.6,66),(31.6,100.3)],4:[(28.5,29.5),(60.7,29.5),(28.5,104.5),(60.7,104.5)],5:[(28.3,28.4),(60.8,28.4),(44.5,66.6),(28.3,104.5),(60.8,104.5)],6:[(x,y) for y in (28.6,66.6,104.6) for x in (28.2,60.8)],7:[(28.9,27.5),(60.3,27.5),(44.6,52.5),(28.9,78),(60.3,78),(28.9,105),(60.3,105)]}
