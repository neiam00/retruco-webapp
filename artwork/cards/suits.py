def coin():
    b = c(0,0,15, '#f6c537', INK, .54)
    b += c(0,0,14.42,'url(#coin-field)', '#cc8e1b', .21)
    # Individual flutes give the die a dark milled edge even on the small coins.
    for j in range(70):
        b+=g(p('M-.20 -15.20 L.12 -15.38 L.34 -14.73 L.08 -14.17Z','#453523',.09),
             f'rotate({j*360/70:.2f})')
    b += line('M-11.38 8.93 A14.48 14.48 0 0 1 -4.91 -13.59',.28,'#ffdd64')
    for j in range(64):
        # Fine interrupted lines cast a warm shadow down the left shoulder of
        # the field, leaving the upper right gleaming as it turns in the light.
        a = pi*(.42 + 1.06*j/63)
        r = 14.03
        cuts = .21 + .69*(sin(pi*j/63)**2)
        b += line(f'M{r*cos(a):.2f} {r*sin(a):.2f} q{-cos(a)*cuts + sin(a)*.13:.2f} '
                  f'{-sin(a)*cuts-cos(a)*.13:.2f} {-2.12*cos(a)*cuts:.2f} {-2.12*sin(a)*cuts:.2f}',
                  .16,'#b58225')
    return b+put(cameo(),-.22,.6,1.08)

